/**
 * @brief Function that converts the parameter raw_temp which is in hex (11 bits) to celsius 
 *        by calculating the appropriate conversion_factor and calculating the ADC_voltage and then answer as celsius
 * 
 * @param raw_temp 11 bits of RESULT of ADC_BASE #0x04 offset. Hex 
 * @return float answer in celsius given param
 */
float asm_convert_raw_temp_to_celsius(uint16_t raw_temp) {
    const float conversion_factor = 3.3f / (1 << 12);
    float answer = 27 - ( ( (raw_temp * conversion_factor) - 0.706) / 0.001721 ); // Temperature approximation
    // T = 27 - (ADC_voltage - 0.706)/0.001721 
    printf("The Temperature is %f degrees Celsius\n", answer);
    if (answer >= 25) { // if degrees 25 or more
        set_rgb_led(RGB_RED); // red for hot
    }
    else if (answer >= 24) { // if degrees 24 or more
        set_rgb_led(RGB_ORANGE); // green for medium
    }
    else { // else degrees cool
        set_rgb_led(RGB_GREEN); // green for cool
    }
    return answer;
}

