/**
 * @brief Wrapper function used to call the underlying PIO
 *        function that pushes the 32-bit RGB colour value
 *        out to the LED serially using the PIO0 block. The
 *        function does not return until all of the data has
 *        been written out.
 * 
 * @param pixel_grb The 32-bit colour value generated by urgb_u32()
 */
static inline void put_pixel(uint32_t pixel_grb) {
    pio_sm_put_blocking(pio0, 0, pixel_grb << 8u);
}

/**
 * @brief Function to generate an unsigned 32-bit composit GRB
 *        value by combining the individual 8-bit paramaters for
 *        red, green and blue together in the right order.
 * 
 * @param r     The 8-bit intensity value for the red component
 * @param g     The 8-bit intensity value for the green component
 * @param b     The 8-bit intensity value for the blue component
 * @return uint32_t Returns the resulting composit 32-bit RGB value
 */
static inline uint32_t urgb_u32(uint8_t r, uint8_t g, uint8_t b) {
    return  ((uint32_t) (r) << 8)  |
            ((uint32_t) (g) << 16) |
            (uint32_t) (b);
}

/**
 * @brief   		Function to set the colour of the RGB LED on the Pi Pico 
 *          		given a colour parameter, or to turn the RGB LED off.
 * 
 * @param colour    An integer value corresponding to a set colour used by the program.
 */
void set_rgb_led(int colour) {

    // Switch statement below checks what parameter has been passed and sets the RGB LED to the desired colour/state.
    switch(colour) {
        case RGB_GREEN:
            // Set the colour to GREEN.
            put_pixel(urgb_u32(0x00, 0x7F, 0x00));
            break;

        case RGB_RED:
            // Set the colour to RED.
            put_pixel(urgb_u32(0x7F, 0x00, 0x00));
            break;

        case RGB_ORANGE:
            // Set the colour to ORANGE.
            put_pixel(urgb_u32(0x99, 0x4C, 0x00));
            break;
    }
}

